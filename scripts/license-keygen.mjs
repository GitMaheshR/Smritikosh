// One-time: creates the owner's licence key pair.
//   private key -> %USERPROFILE%\Documents\Smritikosh-license\smritikosh-private-key.json   (NEVER share, back it up)
//   public key  -> apps/ui/src/license/publicKey.ts                                         (goes into the app)
// Refuses to overwrite an existing private key: replacing it would invalidate every activation code already issued.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const folder = process.env.SMRITIKOSH_LICENSE_DIR || path.join(os.homedir(), 'Documents', 'Smritikosh-license');
const privatePath = path.join(folder, 'smritikosh-private-key.json');
const publicPath = path.join(root, 'apps', 'ui', 'src', 'license', 'publicKey.ts');

if (fs.existsSync(privatePath)) {
  console.error(`A licence key already exists at ${privatePath}. Nothing was changed.`);
  console.error('Replacing it would make every activation code you have issued stop working.');
  process.exit(1);
}

const pair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
const privateJwk = await crypto.subtle.exportKey('jwk', pair.privateKey);
const publicJwk = await crypto.subtle.exportKey('jwk', pair.publicKey);

fs.mkdirSync(folder, { recursive: true });
fs.writeFileSync(privatePath, JSON.stringify(privateJwk, null, 2));
fs.mkdirSync(path.dirname(publicPath), { recursive: true });
fs.writeFileSync(
  publicPath,
  `// Generated by scripts/license-keygen.mjs. The public half of the licence key: it can check activation codes, never make them.\n` +
    `export const PUBLIC_KEY_JWK: JsonWebKey = { kty: '${publicJwk.kty}', crv: '${publicJwk.crv}', x: '${publicJwk.x}', y: '${publicJwk.y}' };\n`,
);

console.log('Licence key pair created.');
console.log(`  secret key : ${privatePath}`);
console.log(`  public key : ${publicPath}`);
console.log('Back up the secret key file (USB drive or your own cloud). If it is lost, no new codes can be made.');
